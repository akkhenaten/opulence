// One-off import of the Emergency guide handover pack into the app.
// Usage: node scripts/emergency-import.mjs /path/to/unzipped-pack
// Writes src/pages/guide/emergency/screens.js and copies the art to public/emergency (+ 720px WebP).
// The wording is copied byte for byte: it is draft clinical copy and must not be edited here.
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const pack = process.argv[2];
if (!pack || !existsSync(join(pack, 'screens.json'))) { console.error('Pass the unzipped pack folder'); process.exit(1); }
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pub = join(root, 'public/emergency');
mkdirSync(pub, { recursive: true });

// Declared actions in the register, as tokens the guide understands
const ACTIONS = { Dialler: '@dial', 'Previous screen': '@back', 'retain last screen': '@resume', End: '@end', 'out-of-scope signposting': '@unwritten', 'no journey built yet': null };
const parseButtons = (s) => String(s || '').split(' | ').map((p) => p.trim()).filter(Boolean).map((p) => {
  const [label, dest] = p.split(' -> ').map((x) => x.trim());
  return { label, to: dest in ACTIONS ? ACTIONS[dest] : dest };
});
const art = (f) => (f ? f.toLowerCase() : null);

const rows = JSON.parse(readFileSync(join(pack, 'screens.json'), 'utf8'));
const CARDS = [];
const SCREENS = {};
for (const r of rows) {
  if (r.screen_id === 'S00') {
    const b = parseButtons(r.buttons)[0];
    CARDS.push({ key: r.illustration_asset.replace('card-', ''), title: r.title.replace(/^Card \d+:\s*(.)/, (_m, c) => c.toUpperCase()), art: art(r.illustration_file), to: b?.to || null });
    continue;
  }
  const unwritten = /^Structure only/i.test(r.content_status || '');
  SCREENS[r.screen_id] = {
    id: r.screen_id, type: r.screen_type, title: r.title,
    // A structure note addressed to the reviewer is never shown as copy
    text: unwritten ? '' : r.wording_exact,
    art: art(r.illustration_file), variants: (r.variants || '').split(/\s+/).filter(Boolean).map(art),
    buttons: parseButtons(r.buttons), clinical: r.clinical_status || '', status: r.content_status || '', unwritten,
  };
}

// M03: the four drafted variants, each its own screen, shown with "scope not decided"
const md = readFileSync(join(pack, 'M03-VARIANTS.md'), 'utf8');
const m03 = SCREENS.M03;
const variantRe = /^## (.+?), art `m03-(\w+)`\s*\n+```\n([\s\S]*?)\n```/gm;
const letters = { fracture: 'a', burn: 'b', head: 'c', eye: 'd' };
const picks = [];
for (const [, heading, key, body] of md.matchAll(variantRe)) {
  const id = `M03${letters[key]}`;
  SCREENS[id] = {
    id, type: 'clinical module', title: heading, text: body, art: `m03${letters[key]}-${key}.png`, variants: [],
    buttons: m03.buttons.filter((b) => ['M04', 'M05'].includes(b.to)), clinical: m03.clinical, status: 'Draft - sourced, pending sign-off', unwritten: false, scopeUndecided: true,
  };
  picks.push({ label: heading, to: id });
}
if (picks.length !== 4) throw new Error(`Expected 4 M03 variants, found ${picks.length}`);
m03.buttons = [...picks, ...m03.buttons.filter((b) => b.to === '@unwritten')];
m03.art = null;

const out = `// GENERATED by scripts/emergency-import.mjs from the Emergency guide handover pack. Do not edit by hand.
// The wording is draft clinical copy pending sign-off: re-import, never rewrite.
export const CARDS = ${JSON.stringify(CARDS, null, 1)};
export const SCREENS = ${JSON.stringify(SCREENS, null, 1)};
`;
writeFileSync(join(root, 'src/pages/guide/emergency/screens.js'), out);

// Art: every file ships (including the ones reserved for other scenarios), plus a 720px WebP of each PNG
for (const f of readdirSync(join(pack, 'assets'))) {
  const to = join(pub, f.toLowerCase());
  copyFileSync(join(pack, 'assets', f), to);
  if (f.endsWith('.png')) execFileSync('convert', [to, '-resize', '720x720', '-quality', '80', to.replace(/\.png$/, '.webp')]);
}
console.log(`${CARDS.length} cards, ${Object.keys(SCREENS).length} screens, art in public/emergency`);
